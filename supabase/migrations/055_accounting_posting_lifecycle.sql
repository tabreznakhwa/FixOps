-- Line items are part of a posted document's accounting substance. Draft invoice
-- lines remain editable, but posted invoice and purchase-invoice lines cannot be
-- changed or deleted outside a sanctioned lifecycle transaction.
create or replace function public.guard_posted_accounting_line()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_posting_sequence bigint;
begin
  if coalesce(current_setting('fixops.allow_accounting_lifecycle_write', true), '') = 'true' then
    return case when tg_op = 'DELETE' then old else new end;
  end if;

  if tg_table_name = 'invoice_items' then
    select i.posting_sequence into v_posting_sequence
    from public.invoices i
    where i.id = coalesce(new.invoice_id, old.invoice_id);
