    p_actor_id, v_batch_id, nullif(btrim(p_notes), '')
  ) returning id into v_posting_id;
  return query select v_id, v_posting_id;
end $$;

create or replace function public.collect_opening_payable(
  p_org_id uuid, p_actor_id uuid, p_opening_payable_id uuid,
  p_supplier_id uuid, p_payment_date date, p_amount_paid numeric,
  p_payment_mode text, p_reference_number text
)
returns table(supplier_payment_id uuid, posting_id uuid, balance_due numeric)
language plpgsql security definer set search_path = public
as $$
declare
  v_kw_date date := (now() at time zone 'Asia/Kuwait')::date;
  v_opening record; v_supplier_name text; v_payment_id uuid; v_posting_id uuid;
  v_seq bigint; v_balance numeric; v_batch_id text := gen_random_uuid()::text;
begin
  perform public.assert_accounting_actor(p_org_id, p_actor_id, array['owner','admin','manager']);
  perform set_config('fixops.allow_accounting_lifecycle_write', 'true', true);
  if p_payment_date is null or p_payment_date > v_kw_date then raise exception 'A non-future payment date is required'; end if;
  if p_amount_paid is null or p_amount_paid <= 0 or scale(p_amount_paid) > 3 then raise exception 'A positive 3-decimal amount is required'; end if;
  if p_payment_mode is null
     or p_payment_mode not in ('cash', 'bank_transfer', 'card', 'pos', 'cheque', 'online', 'other', 'knet') then
    raise exception 'Payment mode is invalid';
  end if;
  if to_regclass('public.opening_payables') is null then raise exception 'Opening payables are not configured'; end if;
  if p_supplier_id is null then raise exception 'Supplier is required'; end if;
  select op.id, op.supplier_id, op.bill_ref, op.balance_due,
         op.reversal_posting_id, op.posting_sequence
  into v_opening
  from public.opening_payables op
  where op.id = p_opening_payable_id
    and op.organization_id = p_org_id
  for update;
  if not found or v_opening.reversal_posting_id is not null then raise exception 'Opening payable not found or reversed'; end if;
  if v_opening.posting_sequence is null then raise exception 'Opening payable has no accounting posting'; end if;
  if v_opening.supplier_id is distinct from p_supplier_id then raise exception 'Opening payable does not belong to supplier'; end if;
  if p_amount_paid > v_opening.balance_due then raise exception 'Payment exceeds opening payable balance'; end if;
  select s.supplier_name into v_supplier_name from public.suppliers s
  where s.id = p_supplier_id and s.organization_id = p_org_id;
  if not found then raise exception 'Supplier does not belong to this organization'; end if;
  v_seq := public.next_posting_sequence(p_org_id); v_balance := v_opening.balance_due - p_amount_paid;
  insert into public.supplier_payments (
    organization_id, supplier_id, opening_payable_id, payment_date,
    amount_paid, discount_amount, payment_mode, reference_number, notes, paid_by,
    posting_date, posting_sequence, posted_at, posted_by, posting_batch_id,
    posting_provenance
  ) values (
    p_org_id, p_supplier_id, p_opening_payable_id, p_payment_date, p_amount_paid, 0,
    p_payment_mode::public.payment_mode, coalesce(nullif(btrim(p_reference_number), ''), v_opening.bill_ref),
    'Opening payable payment — ' || v_opening.bill_ref, p_actor_id, v_kw_date,
    v_seq, now(), p_actor_id, v_batch_id, 'live'
  ) returning id into v_payment_id;
  insert into public.accounting_postings (
    organization_id, ledger, party_id, party_name, posting_date, document_date,
    reference_number, description, posting_sequence, event_type, debit_amount,
    credit_amount, source_type, source_id, provenance, posted_at, posted_by, batch_id
  ) values (
    p_org_id, 'ap', p_supplier_id, v_supplier_name, v_kw_date, p_payment_date,
    coalesce(nullif(btrim(p_reference_number), ''), v_opening.bill_ref),
    'Opening payable payment — ' || v_opening.bill_ref, v_seq, 'payment',
    p_amount_paid, 0, 'supplier_payment', v_payment_id, 'live', now(), p_actor_id, v_batch_id
  ) returning id into v_posting_id;
  update public.opening_payables set balance_due = v_balance where id = p_opening_payable_id;
  return query select v_payment_id, v_posting_id, v_balance;
end $$;

create or replace function public.reverse_opening_payable(
  p_org_id uuid, p_actor_id uuid, p_opening_payable_id uuid, p_reason text
)
returns table(reversed boolean, posting_id uuid)
language plpgsql security definer set search_path = public
as $$
declare
  v_kw_date date := (now() at time zone 'Asia/Kuwait')::date;
  v_opening record; v_original accounting_postings%rowtype; v_posting_id uuid;
  v_seq bigint; v_reason text := nullif(btrim(p_reason), '');
