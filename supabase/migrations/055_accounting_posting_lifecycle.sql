create table if not exists public.accounting_postings (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  ledger text not null check (ledger in ('ar', 'ap')),
  party_id uuid not null,
  party_name text,
  posting_date date not null,
  document_date date,
  reference_number text,
  description text,
  posted_at timestamptz,
  posted_by uuid references public.users(id) on delete set null,
  posting_sequence bigint not null,
  event_type text not null check (
    event_type in ('opening_balance', 'invoice', 'credit_note', 'payment',
                   'advance', 'refund', 'write_off', 'adjustment', 'reversal')
  ),
  debit_amount numeric(13,3) not null default 0 check (debit_amount >= 0),
  credit_amount numeric(13,3) not null default 0 check (credit_amount >= 0),
  source_type text,
  source_id uuid,
  reversal_of uuid,
  provenance text not null default 'live' check (provenance in ('live', 'inferred')),
  batch_id text,
  notes text,
  created_at timestamptz not null default now(),
  check (
    (debit_amount > 0 and credit_amount = 0)
    or (credit_amount > 0 and debit_amount = 0)
  )
);

