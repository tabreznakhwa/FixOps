-- A supplier settlement can produce separate cash and discount postings. Its
-- source keeps the first reversal for compatibility and the reversal batch as
-- the complete audit identity; prove every historically cancelled component is
-- present in that one batch before installing the write guards.
do $$
declare
  v_invalid record;
begin
  select sp.id, sp.organization_id, sp.reversal_batch_id,
         expected.component_count as expected_count,
         coalesce(actual.component_count, 0) as actual_count
  into v_invalid
  from public.supplier_payments sp
  cross join lateral (
    select (case when sp.amount_paid > 0 then 1 else 0 end)
         + (case when coalesce(sp.discount_amount, 0) > 0 then 1 else 0 end)
      as component_count
  ) expected
  left join lateral (
    select count(*)::integer as component_count
    from public.accounting_postings original
    join public.accounting_postings reversal on reversal.reversal_of = original.id
    where original.organization_id = sp.organization_id
      and original.source_id = sp.id
      and original.source_type in ('supplier_payment', 'supplier_payment_discount')
      and original.reversal_of is null
      and reversal.batch_id is not distinct from sp.reversal_batch_id
  ) actual on true
  where sp.supplier_advance_id is null
    and sp.is_cancelled = true
    and (
      expected.component_count = 0
      or sp.reversal_posting_id is null
      or sp.reversal_batch_id is null
      or coalesce(actual.component_count, 0) <> expected.component_count
    )
  order by sp.organization_id, sp.id
  limit 1;

  if found then
    raise exception
      'Cancelled supplier payment % has an incomplete reversal batch % (% of % components). Repair the source/journal lifecycle before rerunning migration 055.',
      v_invalid.id,
      v_invalid.reversal_batch_id,
      v_invalid.actual_count,
      v_invalid.expected_count;
  end if;
end
$$;

