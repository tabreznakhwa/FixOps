    nullif(btrim(p_notes), '')
  ) returning id into v_posting_id;
  return query select v_advance_id, v_number, v_posting_id;
end;
$$;

create or replace function public.cancel_supplier_advance(
  p_org_id uuid,
  p_actor_id uuid,
  p_supplier_advance_id uuid,
  p_reason text
)
returns table(cancelled boolean, posting_id uuid)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_advance supplier_advances%rowtype;
  v_original accounting_postings%rowtype;
  v_kw_date date := (now() at time zone 'Asia/Kuwait')::date;
  v_reason text := nullif(btrim(p_reason), '');
  v_seq bigint;
  v_posting_id uuid;
  v_batch_id text := gen_random_uuid()::text;
begin
  perform public.assert_accounting_actor(p_org_id, p_actor_id, array['owner', 'admin', 'manager']);
  perform set_config('fixops.allow_accounting_lifecycle_write', 'true', true);
  if v_reason is null then raise exception 'Cancellation reason is required'; end if;

  select * into v_advance
  from public.supplier_advances sa
  where sa.id = p_supplier_advance_id and sa.organization_id = p_org_id
  for update;
  if not found then raise exception 'Supplier advance not found'; end if;
  if v_advance.is_cancelled or v_advance.reversal_posting_id is not null then
    raise exception 'Supplier advance is already cancelled';
  end if;
  if v_advance.amount_utilized <> 0 or v_advance.balance <> v_advance.amount then
    raise exception 'Unapply every supplier advance allocation before cancellation';
  end if;
  perform sp.id
  from public.supplier_payments sp
  where sp.organization_id = p_org_id
    and sp.supplier_advance_id = p_supplier_advance_id
    and sp.is_cancelled = false
  order by sp.id
  for update of sp;
  if found then
    raise exception 'Unapply every supplier advance allocation before cancellation';
  end if;

  select * into v_original
  from public.accounting_postings j
  where j.organization_id = p_org_id
    and j.ledger = 'ap'
    and j.party_id = v_advance.supplier_id
    and j.source_type = 'supplier_advance'
    and j.source_id = p_supplier_advance_id
    and j.reversal_of is null
    and j.batch_id is not distinct from v_advance.posting_batch_id
    and j.event_type = 'advance'
    and j.debit_amount = v_advance.amount
    and j.credit_amount = 0
    and j.posting_sequence = v_advance.posting_sequence
    and j.posting_date = v_advance.posting_date
    and j.document_date is not distinct from v_advance.advance_date
    and j.reference_number is not distinct from v_advance.advance_number
    and j.provenance = v_advance.posting_provenance
    and j.posted_at is not distinct from v_advance.posted_at
    and j.posted_by is not distinct from v_advance.posted_by
    and not exists (
      select 1 from public.accounting_postings r where r.reversal_of = j.id
    )
  for share;
  if not found
     or exists (
       select 1
       from public.accounting_postings other
       where other.organization_id = p_org_id
         and other.source_type = 'supplier_advance'
         and other.source_id = p_supplier_advance_id
         and other.reversal_of is null
         and other.id <> v_original.id
     ) then
    raise exception 'Supplier advance accounting posting does not match the recorded advance';
  end if;

  v_seq := public.next_posting_sequence(p_org_id);
  insert into public.accounting_postings (
    organization_id, ledger, party_id, party_name, posting_date, document_date,
    reference_number, description, posting_sequence, event_type, debit_amount,
    credit_amount, source_type, source_id, reversal_of, provenance, posted_at,
    posted_by, batch_id, notes
  ) values (
    p_org_id, 'ap', v_original.party_id, v_original.party_name, v_kw_date,
    v_original.document_date, v_original.reference_number,
    'Reversal — ' || v_original.description, v_seq, 'reversal',
    v_original.credit_amount, v_original.debit_amount, 'supplier_advance',
    p_supplier_advance_id, v_original.id, 'live', now(), p_actor_id,
    v_batch_id, v_reason
  ) returning id into v_posting_id;

  update public.supplier_advances
  set is_cancelled = true,
      cancelled_reason = v_reason,
      cancelled_by = p_actor_id,
      cancelled_at = now(),
      reversal_posting_id = v_posting_id
  where id = p_supplier_advance_id;

  return query select true, v_posting_id;
end;
$$;

