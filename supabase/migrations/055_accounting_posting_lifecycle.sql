create or replace function public.record_opening_payable(
  p_org_id uuid, p_actor_id uuid, p_supplier_id uuid, p_bill_ref text,
  p_bill_date date, p_due_date date, p_amount numeric, p_notes text
)
returns table(opening_payable_id uuid, posting_id uuid)
language plpgsql security definer set search_path = public
as $$
declare
  v_kw_date date := (now() at time zone 'Asia/Kuwait')::date;
  v_id uuid; v_posting_id uuid; v_seq bigint; v_supplier_name text;
  v_batch_id text := gen_random_uuid()::text;
