    from public.purchase_invoices pi
    where pi.id = coalesce(new.purchase_invoice_id, old.purchase_invoice_id);
  end if;

  if v_posting_sequence is not null then
    raise exception 'Posted accounting document lines are immutable; cancel and replace the document';
  end if;

  return case when tg_op = 'DELETE' then old else new end;
end;
$$;
