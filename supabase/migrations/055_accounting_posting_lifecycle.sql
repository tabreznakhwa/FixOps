-- The shared global posting sequence for an organization. Serialized by an
-- advisory lock so concurrent postings cannot collide on the unique index.
create or replace function public.next_posting_sequence(p_org_id uuid)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_next bigint;
begin
  perform pg_advisory_xact_lock(hashtextextended('fixops.posting-seq:' || p_org_id::text, 0));
  select coalesce(max(posting_sequence), 0) + 1
  into v_next
  from public.accounting_postings
  where organization_id = p_org_id;
  return v_next;
end;
$$;

