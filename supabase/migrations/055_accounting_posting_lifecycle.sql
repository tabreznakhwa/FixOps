with candidates as (
  select b.*
  from _postings_backfill b
  where not exists (
    select 1
    from public.accounting_postings existing
    where existing.organization_id = b.organization_id
      and existing.source_type = b.source_type
      and existing.source_id = b.source_id
      and existing.reversal_of is null
  )
),
org_max as (
  select c.organization_id, coalesce(max(j.posting_sequence), 0) as max_sequence
  from (select distinct organization_id from candidates) c
  left join public.accounting_postings j on j.organization_id = c.organization_id
  group by c.organization_id
)
insert into public.accounting_postings (
  organization_id, ledger, party_id, party_name, posting_date, document_date,
  reference_number, description, event_type, debit_amount, credit_amount,
  source_type, source_id, posting_sequence, provenance, posted_at, posted_by, notes
)
select b.organization_id, b.ledger, b.party_id, b.party_name, b.posting_date,
       b.document_date, b.reference_number, b.description, b.event_type,
       b.debit_amount, b.credit_amount, b.source_type, b.source_id,
       m.max_sequence + row_number() over (
         partition by b.organization_id
         order by b.posting_date, b.source_rank, b.source_type, b.party_id, b.source_id
