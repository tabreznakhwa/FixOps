-- Purchase orders are procurement commitments, never AP settlement targets.
-- Stop rather than silently journal legacy PO-linked cash as an ordinary AP
-- debit: each row must first be reconciled to a posted purchase invoice or
-- reclassified as a supplier advance in a controlled data-repair migration.
do $$
declare
  v_legacy_payment record;
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'supplier_payments'
      and column_name = 'purchase_order_id'
  ) then
    execute $query$
      select id, organization_id, supplier_id, purchase_order_id,
             is_cancelled, amount_paid, discount_amount
      from public.supplier_payments
      where purchase_order_id is not null
      order by is_cancelled, organization_id, id
      limit 1
    $query$
    into v_legacy_payment;

    if found then
      raise exception
        'Legacy supplier payment % is allocated to purchase order % (org %, supplier %, cancelled %, cash %, discount %). Reconcile every PO-linked row, including historical cancellations, to a posted purchase invoice or supplier advance before rerunning migration 055.',
        v_legacy_payment.id,
        v_legacy_payment.purchase_order_id,
        v_legacy_payment.organization_id,
        v_legacy_payment.supplier_id,
        v_legacy_payment.is_cancelled,
        v_legacy_payment.amount_paid,
        v_legacy_payment.discount_amount;
    end if;
  end if;
end
$$;

