-- Make the self-reference restrictive even when this migration resumes after an
-- earlier draft that created it with ON DELETE SET NULL.
do $$
declare
  v_constraint_name text;
begin
  select c.conname into v_constraint_name
  from pg_constraint c
  join pg_attribute a
    on a.attrelid = c.conrelid and a.attnum = any(c.conkey)
  where c.conrelid = 'public.accounting_postings'::regclass
    and c.contype = 'f'
    and c.confrelid = 'public.accounting_postings'::regclass
    and a.attname = 'reversal_of'
  order by c.conname
  limit 1;

  if v_constraint_name is not null then
    execute format(
      'alter table public.accounting_postings drop constraint %I',
      v_constraint_name
    );
  end if;

  alter table public.accounting_postings
    add constraint accounting_postings_reversal_of_fkey
    foreign key (reversal_of) references public.accounting_postings(id)
    on delete restrict;
end
$$;

