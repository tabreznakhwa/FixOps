create or replace function public.issue_customer_invoice(
  p_org_id uuid,
  p_actor_id uuid,
  p_invoice_id uuid
)
returns table(invoice_id uuid, posting_id uuid)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_kw_date date := (now() at time zone 'Asia/Kuwait')::date;
  v_invoice invoices%rowtype;
  v_customer_name text;
  v_posting_id uuid;
  v_seq bigint;
  v_existing_paid numeric;
  v_batch_id text := gen_random_uuid()::text;
begin
  perform public.assert_accounting_actor(p_org_id, p_actor_id, array['owner', 'admin', 'manager']);
  perform set_config('fixops.allow_accounting_lifecycle_write', 'true', true);

  select * into v_invoice
  from public.invoices i
  where i.id = p_invoice_id and i.organization_id = p_org_id
  for update;
  if not found then raise exception 'Invoice not found'; end if;
  if v_invoice.status <> 'draft' then raise exception 'Only draft invoices can be issued'; end if;
  if v_invoice.total_amount is null or v_invoice.total_amount <= 0 then
    raise exception 'Only invoices with a positive total can be issued';
  end if;

  select coalesce(nullif(c.company_name, ''), c.full_name, c.id::text)
  into v_customer_name
  from public.customers c
  where c.id = v_invoice.customer_id and c.organization_id = p_org_id;
  if not found then raise exception 'Invoice customer does not belong to this organization'; end if;

  v_seq := public.next_posting_sequence(p_org_id);
  insert into public.accounting_postings (
    organization_id, ledger, party_id, party_name, posting_date, document_date,
    reference_number, description, posting_sequence, event_type, debit_amount,
    credit_amount, source_type, source_id, provenance, posted_at, posted_by,
    batch_id, notes
  ) values (
    p_org_id, 'ar', v_invoice.customer_id, v_customer_name, v_kw_date,
    v_invoice.invoice_date, v_invoice.invoice_number,
    case when v_invoice.invoice_type = 'credit_note' then 'Credit Note ' else 'Invoice ' end || v_invoice.invoice_number,
    v_seq, case when v_invoice.invoice_type = 'credit_note' then 'credit_note' else 'invoice' end,
    case when v_invoice.invoice_type = 'credit_note' then 0 else v_invoice.total_amount end,
    case when v_invoice.invoice_type = 'credit_note' then v_invoice.total_amount else 0 end,
    'invoice', v_invoice.id, 'live', now(), p_actor_id, v_batch_id, v_invoice.notes
  ) returning id into v_posting_id;

  update public.invoices
  set status = 'issued', posting_date = v_kw_date, posting_sequence = v_seq,
      posted_at = now(), posted_by = p_actor_id, posting_batch_id = v_batch_id,
      posting_provenance = 'live', updated_at = now()
  where id = p_invoice_id;

  if v_invoice.work_order_id is not null then
    -- Link receipts collected against the work order before the invoice existed.
    -- The receipt posting remains immutable; this changes allocation only.
    update public.payments p
    set invoice_id = v_invoice.id
    where p.organization_id = p_org_id
      and p.work_order_id = v_invoice.work_order_id
      and p.customer_id = v_invoice.customer_id
      and p.invoice_id is null
      and p.is_cancelled = false
      and p.is_advance = false;

    select coalesce(sum(p.amount_received), 0)
    into v_existing_paid
    from public.payments p
    where p.invoice_id = v_invoice.id and p.is_cancelled = false;

    if v_existing_paid < 0 or v_existing_paid > v_invoice.total_amount then
      raise exception 'Pre-invoice receipts exceed the invoice total; allocate the excess as an advance';
    end if;

    update public.invoices i
    set amount_paid = v_existing_paid,
        balance_due = i.total_amount - v_existing_paid,
        status = case
          when v_existing_paid = i.total_amount then 'paid'::public.invoice_status
          when v_existing_paid > 0 then 'partial'::public.invoice_status
          else 'issued'::public.invoice_status
        end,
        updated_at = now()
    where i.id = v_invoice.id;

    update public.work_orders wo
    set status = case when (select status from public.invoices where id = v_invoice.id) = 'paid' then 'paid'::public.work_order_status else 'invoiced'::public.work_order_status end,
        payment_status = case
          when (select status from public.invoices where id = v_invoice.id) = 'paid' then 'paid'::public.payment_status
          when (select status from public.invoices where id = v_invoice.id) = 'partial' then 'partial'::public.payment_status
          else 'unpaid'::public.payment_status
        end
    where wo.id = v_invoice.work_order_id and wo.organization_id = p_org_id;
  end if;

  return query select v_invoice.id, v_posting_id;
end;
$$;

