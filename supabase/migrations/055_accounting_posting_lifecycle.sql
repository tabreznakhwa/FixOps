-- Use one supported payment-mode set across purchase documents and settlements.
do $$
declare
  v_constraint record;
begin
  -- Drop the known migration-owned name explicitly as well as any older checks
  -- attached to payment_mode. A CHECK expression can have a null conkey, so the
  -- pg_attribute scan alone is not a reliable resumability guard.
  alter table public.purchase_invoices
    drop constraint if exists purchase_invoices_payment_mode_check;

  for v_constraint in
    select c.conname
    from pg_constraint c
    join pg_attribute a
      on a.attrelid = c.conrelid and a.attnum = any(c.conkey)
    where c.conrelid = 'public.purchase_invoices'::regclass
      and c.contype = 'c'
      and a.attname = 'payment_mode'
  loop
    execute format(
      'alter table public.purchase_invoices drop constraint %I',
      v_constraint.conname
    );
  end loop;

  alter table public.purchase_invoices
    add constraint purchase_invoices_payment_mode_check
    check (
      payment_mode is null
      or payment_mode in (
        'cash', 'bank_transfer', 'card', 'pos', 'cheque', 'online', 'other', 'knet'
      )
    );
end
$$;

