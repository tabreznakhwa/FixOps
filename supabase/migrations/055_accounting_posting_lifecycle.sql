create or replace function public.create_purchase_invoice(
  p_org_id uuid,
  p_actor_id uuid,
  p_supplier_id uuid,
  p_supplier_name text,
  p_supplier_invoice_number text,
  p_invoice_date date,
  p_due_date date,
  p_payment_type text,
  p_payment_mode text,
  p_discount_amount numeric,
  p_notes text,
  p_items jsonb
)
returns table(purchase_invoice_id uuid, invoice_number text, posting_id uuid)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_kw_date date := (now() at time zone 'Asia/Kuwait')::date;
  v_number text;
  v_supplier_name text;
  v_invoice_id uuid;
  v_posting_id uuid;
  v_payment_id uuid;
  v_payment_posting_id uuid;
  v_seq bigint;
  v_payment_seq bigint;
  v_subtotal numeric := 0;
  v_discount numeric := coalesce(p_discount_amount, 0);
  v_total numeric;
  v_batch_id text := gen_random_uuid()::text;
  v_payment_batch_id text := gen_random_uuid()::text;
  v_item jsonb;
  v_item_id uuid;
  v_description text;
  v_quantity numeric;
  v_unit_cost numeric;
  v_stock_before numeric;
  v_stock_after numeric;
  v_previous_purchase_price numeric;
  v_duplicate_item uuid;
begin
  perform public.assert_accounting_actor(p_org_id, p_actor_id, array['owner', 'admin', 'manager']);
  perform set_config('fixops.allow_accounting_lifecycle_write', 'true', true);
  perform set_config('fixops.allow_stock_write', 'true', true);
  if p_invoice_date is null or p_invoice_date > v_kw_date then raise exception 'A non-future invoice date is required'; end if;
  if p_payment_type not in ('cash', 'credit') then raise exception 'Payment type is invalid'; end if;
  if p_payment_type = 'cash' and (
    p_payment_mode is null
    or p_payment_mode not in ('cash', 'bank_transfer', 'card', 'pos', 'cheque', 'online', 'other', 'knet')
  ) then raise exception 'Payment mode is invalid'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'At least one item is required'; end if;
  if v_discount < 0 or scale(v_discount) > 3 then raise exception 'Discount must have at most 3 decimal places'; end if;

  if p_supplier_id is not null then
    select s.supplier_name into v_supplier_name from public.suppliers s
    where s.id = p_supplier_id and s.organization_id = p_org_id;
    if not found then raise exception 'Supplier does not belong to this organization'; end if;
  else
    v_supplier_name := nullif(btrim(p_supplier_name), '');
  end if;

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_quantity := (v_item ->> 'quantity')::numeric;
    v_unit_cost := (v_item ->> 'unit_cost')::numeric;
    if v_quantity <= 0 or v_unit_cost < 0 or scale(v_quantity) > 3 or scale(v_unit_cost) > 3 then
      raise exception 'Item quantities and costs must be valid 3-decimal amounts';
    end if;
    v_subtotal := v_subtotal + v_quantity * v_unit_cost;
  end loop;

  select item_id into v_duplicate_item
  from (
    select nullif(value ->> 'inventory_item_id', '')::uuid as item_id
    from jsonb_array_elements(p_items)
  ) parsed
  where item_id is not null
  group by item_id
  having count(*) > 1
  limit 1;
  if v_duplicate_item is not null then
    raise exception 'Inventory item % appears more than once; combine duplicate lines', v_duplicate_item;
  end if;

  -- Lock every inventory row in one deterministic order before mutating any of
  -- them. This prevents opposite line ordering on concurrent invoices from
  -- producing an avoidable deadlock.
  perform i.id
  from public.inventory_items i
  join (
    select distinct nullif(value ->> 'inventory_item_id', '')::uuid as item_id
    from jsonb_array_elements(p_items)
  ) requested on requested.item_id = i.id
  where i.organization_id = p_org_id
  order by i.id
  for update of i;

  if (
    select count(*) from (
      select distinct nullif(value ->> 'inventory_item_id', '')::uuid as item_id
      from jsonb_array_elements(p_items)
    ) requested where item_id is not null
  ) <> (
    select count(*) from public.inventory_items i
    join (
      select distinct nullif(value ->> 'inventory_item_id', '')::uuid as item_id
      from jsonb_array_elements(p_items)
    ) requested on requested.item_id = i.id
    where i.organization_id = p_org_id
  ) then
    raise exception 'An inventory item does not belong to this organization';
  end if;

  if v_subtotal <= 0 then
    raise exception 'A purchase invoice must have a positive subtotal';
  end if;
  if v_discount >= v_subtotal then
    raise exception 'Discount must be less than the purchase-invoice subtotal';
  end if;
  v_total := v_subtotal - v_discount;
  v_number := public.generate_sequence_number(p_org_id, 'purchase_invoice', 'PINV');

  insert into public.purchase_invoices (
    organization_id, invoice_number, supplier_id, supplier_name,
    supplier_invoice_number, invoice_date, due_date, payment_type, payment_mode,
    subtotal, discount_amount, total_amount, amount_paid, balance_due,
    payment_status, notes, status, created_by
  ) values (
    p_org_id, v_number, p_supplier_id, v_supplier_name,
    nullif(btrim(p_supplier_invoice_number), ''), p_invoice_date, p_due_date,
    p_payment_type, case when p_payment_type = 'cash' then p_payment_mode else null end,
    v_subtotal, v_discount, v_total, 0, v_total, 'unpaid',
    nullif(btrim(p_notes), ''), 'confirmed', p_actor_id
  ) returning id into v_invoice_id;

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_item_id := nullif(v_item ->> 'inventory_item_id', '')::uuid;
    v_description := nullif(btrim(v_item ->> 'description'), '');
    v_quantity := (v_item ->> 'quantity')::numeric;
    v_unit_cost := (v_item ->> 'unit_cost')::numeric;
    if v_item_id is null and v_description is null then raise exception 'Non-inventory items require a description'; end if;

    v_previous_purchase_price := null;
    if v_item_id is not null then
      select current_stock, purchase_price into v_stock_before, v_previous_purchase_price
      from public.inventory_items
      where id = v_item_id and organization_id = p_org_id for update;
      if not found then raise exception 'Inventory item does not belong to this organization'; end if;
      update public.inventory_items
      set current_stock = current_stock + v_quantity,
          purchase_price = case when v_unit_cost > 0 then v_unit_cost else purchase_price end,
          updated_at = now()
      where id = v_item_id
      returning current_stock into v_stock_after;
      insert into public.inventory_transactions (
        organization_id, item_id, transaction_type, quantity, unit_cost, total_cost,
        stock_before, stock_after, reference_type, reference_id, notes, created_by
      ) values (
        p_org_id, v_item_id, 'purchase', v_quantity, v_unit_cost,
        v_quantity * v_unit_cost, v_stock_before, v_stock_after,
        'purchase_invoice', v_invoice_id, 'Purchase Invoice ' || v_number, p_actor_id
      );
    end if;

    insert into public.purchase_invoice_items (
      organization_id, purchase_invoice_id, inventory_item_id, description,
      unit_of_measure, quantity, unit_cost, previous_purchase_price, total_cost, sort_order
    ) values (
      p_org_id, v_invoice_id, v_item_id, coalesce(v_description, 'Inventory item'),
      nullif(btrim(v_item ->> 'unit_of_measure'), ''), v_quantity, v_unit_cost,
      case when v_item_id is not null then v_previous_purchase_price else null end,
      v_quantity * v_unit_cost, coalesce((v_item ->> 'sort_order')::int, 0)
    );
  end loop;

  if p_supplier_id is not null then
    v_seq := public.next_posting_sequence(p_org_id);
    insert into public.accounting_postings (
      organization_id, ledger, party_id, party_name, posting_date, document_date,
      reference_number, description, posting_sequence, event_type, debit_amount,
      credit_amount, source_type, source_id, provenance, posted_at, posted_by, batch_id, notes
    ) values (
      p_org_id, 'ap', p_supplier_id, v_supplier_name, v_kw_date, p_invoice_date,
      v_number, 'Purchase Invoice ' || v_number, v_seq, 'invoice', 0, v_total,
      'purchase_invoice', v_invoice_id, 'live', now(), p_actor_id, v_batch_id,
      nullif(btrim(p_notes), '')
    ) returning id into v_posting_id;
    update public.purchase_invoices set posting_date = v_kw_date,
      posting_sequence = v_seq, posted_at = now(), posted_by = p_actor_id,
      posting_batch_id = v_batch_id, posting_provenance = 'live'
    where id = v_invoice_id;

    if p_payment_type = 'cash' then
      v_payment_seq := public.next_posting_sequence(p_org_id);
      insert into public.supplier_payments (
        organization_id, supplier_id, purchase_invoice_id, payment_date,
        amount_paid, discount_amount, payment_mode, reference_number, notes,
        paid_by, posting_date, posting_sequence, posted_at, posted_by,
        posting_batch_id, posting_provenance, is_automatic
      ) values (
        p_org_id, p_supplier_id, v_invoice_id, p_invoice_date, v_total, 0,
        p_payment_mode::public.payment_mode, nullif(btrim(p_supplier_invoice_number), ''),
        'Purchase Invoice ' || v_number, p_actor_id, v_kw_date, v_payment_seq,
        now(), p_actor_id, v_payment_batch_id, 'live', true
      ) returning id into v_payment_id;
      insert into public.accounting_postings (
        organization_id, ledger, party_id, party_name, posting_date, document_date,
        reference_number, description, posting_sequence, event_type, debit_amount,
        credit_amount, source_type, source_id, provenance, posted_at, posted_by, batch_id
      ) values (
        p_org_id, 'ap', p_supplier_id, v_supplier_name, v_kw_date, p_invoice_date,
        nullif(btrim(p_supplier_invoice_number), ''), 'Supplier Payment — ' || v_number,
        v_payment_seq, 'payment', v_total, 0, 'supplier_payment', v_payment_id,
        'live', now(), p_actor_id, v_payment_batch_id
      ) returning id into v_payment_posting_id;
      update public.purchase_invoices set amount_paid = v_total, balance_due = 0,
        payment_status = 'paid', updated_at = now() where id = v_invoice_id;
    end if;
  end if;

  return query select v_invoice_id, v_number, v_posting_id;
end;
$$;

create or replace function public.cancel_purchase_invoice(
  p_org_id uuid,
  p_actor_id uuid,
  p_purchase_invoice_id uuid,
  p_reason text
)
returns table(cancelled boolean, posting_id uuid, reversed_items integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_kw_date date := (now() at time zone 'Asia/Kuwait')::date;
  v_invoice purchase_invoices%rowtype;
  v_payment supplier_payments%rowtype;
  v_original accounting_postings%rowtype;
  v_line record;
  v_stock_before numeric;
  v_stock_after numeric;
  v_reason text := nullif(btrim(p_reason), '');
  v_seq bigint;
  v_posting_id uuid;
  v_payment_reversal_id uuid;
  v_batch_id text := gen_random_uuid()::text;
  v_payment_reversal_batch_id text := gen_random_uuid()::text;
  v_expected_payment_postings integer;
  v_actual_payment_postings integer;
  v_count integer := 0;
begin
  perform public.assert_accounting_actor(p_org_id, p_actor_id, array['owner', 'admin', 'manager']);
  perform set_config('fixops.allow_accounting_lifecycle_write', 'true', true);
  perform set_config('fixops.allow_stock_write', 'true', true);
  if v_reason is null then raise exception 'Cancellation reason is required'; end if;

  -- Lock the invoice first, then every active settlement row in stable ID order.
  -- Apply/unapply/record paths use the same invoice-before-settlement order.
  select * into v_invoice from public.purchase_invoices
  where id = p_purchase_invoice_id and organization_id = p_org_id for update;
  if not found then raise exception 'Purchase invoice not found'; end if;
  if v_invoice.status = 'cancelled' or v_invoice.reversal_posting_id is not null then raise exception 'Purchase invoice is already cancelled'; end if;

  perform sp.id
  from public.supplier_payments sp
  where sp.organization_id = p_org_id
    and sp.purchase_invoice_id = p_purchase_invoice_id
    and sp.is_cancelled = false
  order by sp.id
  for update of sp;

  if coalesce(v_invoice.amount_paid, 0) > 0 then
    select * into v_payment
    from public.supplier_payments sp
    where sp.organization_id = p_org_id
      and sp.purchase_invoice_id = p_purchase_invoice_id
      and sp.is_automatic = true
      and sp.is_cancelled = false
    order by sp.id
    limit 1;
    if not found
       or coalesce(v_payment.amount_paid, 0) + coalesce(v_payment.discount_amount, 0)
          <> v_invoice.amount_paid
       or exists (
         select 1 from public.supplier_payments other
         where other.organization_id = p_org_id
           and other.purchase_invoice_id = p_purchase_invoice_id
           and other.id <> v_payment.id
           and other.is_cancelled = false
       ) then
      raise exception 'Cancel or reallocate independent supplier settlements first';
    end if;
  end if;

  -- Match creation's inventory lock order so concurrent cancellation and receipt
  -- transactions cannot lock the same items in opposite orders.
  perform i.id
  from public.inventory_items i
  join (
    select distinct pii.inventory_item_id
    from public.purchase_invoice_items pii
    where pii.purchase_invoice_id = p_purchase_invoice_id
      and pii.organization_id = p_org_id
      and pii.inventory_item_id is not null
  ) lines on lines.inventory_item_id = i.id
  where i.organization_id = p_org_id
  order by i.id
  for update of i;

  for v_line in select inventory_item_id, quantity, unit_cost, previous_purchase_price
    from public.purchase_invoice_items where purchase_invoice_id = p_purchase_invoice_id
      and organization_id = p_org_id and inventory_item_id is not null
    order by inventory_item_id
  loop
    select current_stock into v_stock_before from public.inventory_items
    where id = v_line.inventory_item_id and organization_id = p_org_id for update;
    if not found then raise exception 'Inventory item does not belong to this organization'; end if;
    if v_stock_before < v_line.quantity then raise exception 'Cannot cancel purchase invoice because received stock has been used'; end if;
    update public.inventory_items
    set current_stock = current_stock - v_line.quantity,
        purchase_price = coalesce(v_line.previous_purchase_price, purchase_price),
        updated_at = now()
    where id = v_line.inventory_item_id returning current_stock into v_stock_after;
    insert into public.inventory_transactions (
      organization_id, item_id, transaction_type, quantity, unit_cost, total_cost,
      stock_before, stock_after, reference_type, reference_id, notes, created_by
    ) values (
      p_org_id, v_line.inventory_item_id, 'adjustment', -v_line.quantity,
      v_line.unit_cost, v_line.quantity * v_line.unit_cost, v_stock_before,
      v_stock_after, 'purchase_invoice_cancelled', p_purchase_invoice_id,
      'Reversal of cancelled Purchase Invoice ' || v_invoice.invoice_number,
      p_actor_id
    );
    v_count := v_count + 1;
  end loop;

  if v_payment.id is not null then
    v_expected_payment_postings := case when v_payment.amount_paid > 0 then 1 else 0 end
      + case when coalesce(v_payment.discount_amount, 0) > 0 then 1 else 0 end;
    select count(*) into v_actual_payment_postings
    from public.accounting_postings j
    where j.organization_id = p_org_id
      and j.ledger = 'ap'
      and j.party_id = v_payment.supplier_id
      and j.source_id = v_payment.id
      and j.source_type in ('supplier_payment', 'supplier_payment_discount')
      and j.reversal_of is null
      and j.batch_id is not distinct from v_payment.posting_batch_id
      and (
        (j.source_type = 'supplier_payment'
          and j.event_type = 'payment'
          and j.debit_amount = v_payment.amount_paid
          and j.credit_amount = 0)
        or
        (j.source_type = 'supplier_payment_discount'
          and j.event_type = 'adjustment'
          and j.debit_amount = coalesce(v_payment.discount_amount, 0)
          and j.credit_amount = 0)
      )
      and not exists (
        select 1 from public.accounting_postings r where r.reversal_of = j.id
      );

    if v_expected_payment_postings = 0
       or v_actual_payment_postings <> v_expected_payment_postings
       or exists (
         select 1
         from public.accounting_postings j
         where j.organization_id = p_org_id
           and j.ledger = 'ap'
           and j.source_id = v_payment.id
           and j.reversal_of is null
           and (
             j.party_id <> v_payment.supplier_id
             or j.source_type not in ('supplier_payment', 'supplier_payment_discount')
             or j.batch_id is distinct from v_payment.posting_batch_id
             or exists (
               select 1 from public.accounting_postings r where r.reversal_of = j.id
             )
           )
       ) then
      raise exception 'Automatic supplier payment accounting postings do not match the recorded settlement';
    end if;

    v_payment_reversal_id := null;
    for v_original in
      select j.*
      from public.accounting_postings j
      where j.organization_id = p_org_id
        and j.ledger = 'ap'
        and j.source_id = v_payment.id
        and j.source_type in ('supplier_payment', 'supplier_payment_discount')
        and j.reversal_of is null
      order by j.posting_sequence
      for share
    loop
      v_seq := public.next_posting_sequence(p_org_id);
      insert into public.accounting_postings (
        organization_id, ledger, party_id, party_name, posting_date, document_date,
        reference_number, description, posting_sequence, event_type, debit_amount,
        credit_amount, source_type, source_id, reversal_of, provenance, posted_at,
        posted_by, batch_id, notes
      ) values (
        p_org_id, 'ap', v_original.party_id, v_original.party_name, v_kw_date,
        v_original.document_date, v_original.reference_number,
        'Reversal — ' || v_original.description, v_seq, 'reversal',
        v_original.credit_amount, v_original.debit_amount, v_original.source_type,
        v_payment.id, v_original.id, 'live', now(), p_actor_id,
        v_payment_reversal_batch_id, v_reason
      ) returning id into v_payment_reversal_id;
    end loop;
    if v_payment_reversal_id is null then
      raise exception 'Automatic supplier payment has no accounting posting';
    end if;
    update public.supplier_payments
    set is_cancelled = true,
        cancelled_reason = v_reason,
        cancelled_by = p_actor_id,
        cancelled_at = now(),
        reversal_posting_id = v_payment_reversal_id,
        reversal_batch_id = v_payment_reversal_batch_id
    where id = v_payment.id;
  end if;

  if v_invoice.posting_sequence is not null then
    select * into v_original
    from public.accounting_postings j
    where j.organization_id = p_org_id
      and j.source_type = 'purchase_invoice'
      and j.source_id = p_purchase_invoice_id
      and j.reversal_of is null
    for share;
    if not found then
      raise exception 'Purchase invoice has no accounting posting';
    end if;
    if v_original.ledger <> 'ap'
       or v_original.party_id is distinct from v_invoice.supplier_id
       or v_original.event_type <> 'invoice'
       or v_original.debit_amount <> 0
       or v_original.credit_amount <> v_invoice.total_amount
       or v_original.posting_sequence <> v_invoice.posting_sequence
       or v_original.posting_date <> v_invoice.posting_date
       or v_original.document_date <> v_invoice.invoice_date
       or v_original.reference_number is distinct from v_invoice.invoice_number
       or v_original.batch_id is distinct from v_invoice.posting_batch_id
       or v_original.provenance is distinct from v_invoice.posting_provenance
       or v_original.posted_at is distinct from v_invoice.posted_at
       or v_original.posted_by is distinct from v_invoice.posted_by
       or exists (
         select 1 from public.accounting_postings r
         where r.reversal_of = v_original.id
       )
       or exists (
         select 1
         from public.accounting_postings other
         where other.organization_id = p_org_id
           and other.source_type = 'purchase_invoice'
           and other.source_id = p_purchase_invoice_id
           and other.reversal_of is null
           and other.id <> v_original.id
       ) then
      raise exception 'Purchase invoice accounting posting does not match the source';
    end if;
    v_seq := public.next_posting_sequence(p_org_id);
    insert into public.accounting_postings (
      organization_id, ledger, party_id, party_name, posting_date, document_date,
      reference_number, description, posting_sequence, event_type, debit_amount,
      credit_amount, source_type, source_id, reversal_of, provenance, posted_at,
      posted_by, batch_id, notes
    ) values (
      p_org_id, 'ap', v_original.party_id, v_original.party_name, v_kw_date,
      v_original.document_date, v_original.reference_number,
      'Reversal — ' || v_original.description, v_seq, 'reversal',
      v_original.credit_amount, v_original.debit_amount, 'purchase_invoice',
      p_purchase_invoice_id, v_original.id, 'live', now(), p_actor_id,
      v_batch_id, v_reason
    ) returning id into v_posting_id;
  end if;

  update public.purchase_invoices set status = 'cancelled',
    cancelled_reason = v_reason, cancelled_by = p_actor_id, cancelled_at = now(),
    reversal_posting_id = v_posting_id, updated_at = now()
  where id = p_purchase_invoice_id;
  return query select true, v_posting_id, v_count;
end;
$$;

create or replace function public.cancel_supplier_payment(
  p_org_id uuid,
  p_actor_id uuid,
  p_supplier_payment_id uuid,
  p_reason text
)
returns table(cancelled boolean, posting_id uuid, reversed_postings integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_kw_date date := (now() at time zone 'Asia/Kuwait')::date;
  v_payment supplier_payments%rowtype;
  v_invoice purchase_invoices%rowtype;
  v_opening record;
  v_original accounting_postings%rowtype;
  v_reversal_id uuid;
  v_first_reversal_id uuid;
  v_seq bigint;
  v_reason text := nullif(btrim(p_reason), '');
  v_reversal_batch_id text := gen_random_uuid()::text;
  v_reversed integer := 0;
  v_expected_postings integer;
  v_actual_postings integer;
  v_new_paid numeric;
begin
  perform public.assert_accounting_actor(
    p_org_id, p_actor_id, array['owner', 'admin', 'manager']
  );
  perform set_config('fixops.allow_accounting_lifecycle_write', 'true', true);
  if v_reason is null then raise exception 'Cancellation reason is required'; end if;

  -- Read the immutable target first so the document can be locked before the
  -- settlement row. This matches record/apply/cancel purchase-invoice order.
  select * into v_payment
  from public.supplier_payments sp
  where sp.id = p_supplier_payment_id and sp.organization_id = p_org_id;
  if not found then raise exception 'Supplier payment not found'; end if;
  if v_payment.supplier_advance_id is not null then
    raise exception 'Advance allocations must be unapplied through their allocation workflow';
  end if;
  if v_payment.purchase_order_id is not null then
    raise exception 'Legacy purchase-order payments must be reconciled before cancellation';
  end if;
  if v_payment.is_automatic then
    raise exception 'Automatic supplier payments can only be reversed with their purchase invoice';
  end if;
  if v_payment.is_cancelled then raise exception 'Supplier payment is already cancelled'; end if;

  if v_payment.purchase_invoice_id is not null then
    select * into v_invoice
    from public.purchase_invoices pi
    where pi.id = v_payment.purchase_invoice_id
      and pi.organization_id = p_org_id
    for update;
    if not found then raise exception 'Linked purchase invoice not found'; end if;
    if v_invoice.status = 'cancelled' then
      raise exception 'Linked purchase invoice is already cancelled';
    end if;
  elsif v_payment.opening_payable_id is not null then
    select id, amount, balance_due, reversal_posting_id into v_opening
    from public.opening_payables op
    where op.id = v_payment.opening_payable_id
      and op.organization_id = p_org_id
    for update;
    if not found then raise exception 'Linked opening payable not found'; end if;
  end if;

  select * into v_payment
  from public.supplier_payments sp
  where sp.id = p_supplier_payment_id and sp.organization_id = p_org_id
  for update;
  if not found then raise exception 'Supplier payment not found'; end if;
  if v_payment.is_cancelled then raise exception 'Supplier payment is already cancelled'; end if;

  v_expected_postings := case when v_payment.amount_paid > 0 then 1 else 0 end
    + case when coalesce(v_payment.discount_amount, 0) > 0 then 1 else 0 end;
  select count(*) into v_actual_postings
  from public.accounting_postings j
  where j.organization_id = p_org_id
    and j.ledger = 'ap'
    and j.party_id = v_payment.supplier_id
    and j.source_id = p_supplier_payment_id
    and j.source_type in ('supplier_payment', 'supplier_payment_discount')
    and j.reversal_of is null
    and j.batch_id is not distinct from v_payment.posting_batch_id
    and (
      (j.source_type = 'supplier_payment'
        and j.event_type = 'payment'
        and j.debit_amount = v_payment.amount_paid
        and j.credit_amount = 0)
      or
      (j.source_type = 'supplier_payment_discount'
        and j.event_type = 'adjustment'
        and j.debit_amount = coalesce(v_payment.discount_amount, 0)
        and j.credit_amount = 0)
    )
    and not exists (
      select 1 from public.accounting_postings r where r.reversal_of = j.id
    );

  if v_expected_postings = 0
     or v_actual_postings <> v_expected_postings
     or exists (
       select 1
       from public.accounting_postings j
       where j.organization_id = p_org_id
         and j.ledger = 'ap'
         and j.source_id = p_supplier_payment_id
         and j.reversal_of is null
         and (
           j.party_id <> v_payment.supplier_id
           or j.source_type not in ('supplier_payment', 'supplier_payment_discount')
           or j.batch_id is distinct from v_payment.posting_batch_id
           or exists (
             select 1 from public.accounting_postings r where r.reversal_of = j.id
           )
         )
     ) then
    raise exception 'Supplier payment accounting postings do not match the recorded settlement';
  end if;

  for v_original in
    select j.*
    from public.accounting_postings j
    where j.organization_id = p_org_id
      and j.ledger = 'ap'
      and j.source_id = p_supplier_payment_id
      and j.source_type in ('supplier_payment', 'supplier_payment_discount')
      and j.reversal_of is null
    order by j.posting_sequence
    for share
  loop
    v_seq := public.next_posting_sequence(p_org_id);
    insert into public.accounting_postings (
      organization_id, ledger, party_id, party_name, posting_date, document_date,
      reference_number, description, posting_sequence, event_type, debit_amount,
      credit_amount, source_type, source_id, reversal_of, provenance, posted_at,
      posted_by, batch_id, notes
    ) values (
      p_org_id, 'ap', v_original.party_id, v_original.party_name, v_kw_date,
      v_original.document_date, v_original.reference_number,
      'Reversal — ' || v_original.description, v_seq, 'reversal',
      v_original.credit_amount, v_original.debit_amount, v_original.source_type,
      p_supplier_payment_id, v_original.id, 'live', now(), p_actor_id,
      v_reversal_batch_id, v_reason
    ) returning id into v_reversal_id;
    v_first_reversal_id := coalesce(v_first_reversal_id, v_reversal_id);
    v_reversed := v_reversed + 1;
  end loop;

  if v_reversed = 0 then
    raise exception 'Supplier payment has no accounting posting and cannot be reversed';
  end if;

  if v_payment.purchase_invoice_id is not null then
    select coalesce(sum(
      coalesce(sp.amount_paid, 0) + coalesce(sp.discount_amount, 0)
    ), 0)
    into v_new_paid
    from public.supplier_payments sp
    where sp.organization_id = p_org_id
      and sp.purchase_invoice_id = v_payment.purchase_invoice_id
      and sp.id <> p_supplier_payment_id
      and sp.is_cancelled = false;

    if v_new_paid < 0 or v_new_paid > v_invoice.total_amount then
      raise exception 'Purchase invoice allocations do not reconcile to the invoice total';
    end if;

    update public.purchase_invoices
    set amount_paid = v_new_paid,
        balance_due = total_amount - v_new_paid,
        payment_status = case
          when v_new_paid = total_amount then 'paid'
          when v_new_paid > 0 then 'partial'
          else 'unpaid'
        end,
        updated_at = now()
    where id = v_payment.purchase_invoice_id;
  elsif v_payment.opening_payable_id is not null then
    if v_opening.reversal_posting_id is not null then
      raise exception 'Cannot cancel payment for a reversed opening payable';
    end if;

    select coalesce(sum(sp.amount_paid), 0)
    into v_new_paid
    from public.supplier_payments sp
    where sp.organization_id = p_org_id
      and sp.opening_payable_id = v_payment.opening_payable_id
      and sp.id <> p_supplier_payment_id
      and sp.is_cancelled = false;

    if v_new_paid < 0 or v_new_paid > v_opening.amount then
      raise exception 'Opening payable allocations do not reconcile to the opening amount';
    end if;

    update public.opening_payables
    set balance_due = amount - v_new_paid
    where id = v_payment.opening_payable_id;
  end if;

  update public.supplier_payments
  set is_cancelled = true,
      cancelled_reason = v_reason,
      cancelled_by = p_actor_id,
      cancelled_at = now(),
      reversal_posting_id = v_first_reversal_id,
      reversal_batch_id = v_reversal_batch_id
  where id = p_supplier_payment_id;

  return query select true, v_first_reversal_id, v_reversed;
end;
$$;

create or replace function public.record_supplier_payment(
  p_org_id uuid,
  p_actor_id uuid,
  p_supplier_id uuid,
  p_purchase_invoice_id uuid,
  p_payment_date date,
  p_amount_paid numeric,
  p_discount_amount numeric,
  p_payment_mode text,
  p_reference_number text,
  p_notes text
)
returns table(supplier_payment_id uuid, posting_id uuid)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_kw_date date := (now() at time zone 'Asia/Kuwait')::date;
  v_invoice purchase_invoices%rowtype;
  v_supplier_name text;
  v_payment_id uuid;
  v_posting_id uuid;
  v_discount_posting_id uuid;
  v_seq bigint;
  v_source_seq bigint;
  v_discount_seq bigint;
  v_settlement numeric := coalesce(p_amount_paid, 0) + coalesce(p_discount_amount, 0);
  v_new_paid numeric;
  v_batch_id text := gen_random_uuid()::text;
begin
  perform public.assert_accounting_actor(p_org_id, p_actor_id, array['owner', 'admin', 'manager', 'accounts']);
  perform set_config('fixops.allow_accounting_lifecycle_write', 'true', true);
  if p_payment_date is null or p_payment_date > v_kw_date then raise exception 'A non-future payment date is required'; end if;
  if p_amount_paid is null or p_amount_paid < 0 or coalesce(p_discount_amount, 0) < 0
     or v_settlement <= 0 or scale(p_amount_paid) > 3 or scale(coalesce(p_discount_amount, 0)) > 3 then
    raise exception 'A positive settlement with at most 3 decimal places is required';
  end if;
  if p_payment_mode is null
     or p_payment_mode not in ('cash', 'bank_transfer', 'card', 'pos', 'cheque', 'online', 'other', 'knet') then
    raise exception 'Payment mode is invalid';
  end if;
  select s.supplier_name into v_supplier_name from public.suppliers s
  where s.id = p_supplier_id and s.organization_id = p_org_id;
  if not found then raise exception 'Supplier does not belong to this organization'; end if;

  if p_purchase_invoice_id is null then
    if coalesce(p_discount_amount, 0) > 0 then
      raise exception 'Discount requires a linked purchase invoice';
    end if;
    raise exception 'Unallocated supplier cash must be recorded as a supplier advance';
  end if;

  if p_purchase_invoice_id is not null then
    -- Purchase-invoice workflows lock the invoice before their settlement row.
    select * into v_invoice from public.purchase_invoices
    where id = p_purchase_invoice_id and organization_id = p_org_id for update;
    if not found or v_invoice.supplier_id is distinct from p_supplier_id then
      raise exception 'Purchase invoice does not belong to this supplier';
    end if;
    if v_invoice.status = 'cancelled' or v_invoice.posting_sequence is null then
      raise exception 'Supplier payments require a posted, active purchase invoice';
    end if;
    if v_settlement > v_invoice.balance_due then raise exception 'Settlement exceeds invoice balance'; end if;
  end if;

  v_source_seq := public.next_posting_sequence(p_org_id);
  v_seq := v_source_seq;
  insert into public.supplier_payments (
    organization_id, supplier_id, purchase_invoice_id, payment_date,
    amount_paid, discount_amount, payment_mode, reference_number, notes, paid_by,
    posting_date, posting_sequence, posted_at, posted_by, posting_batch_id,
    posting_provenance
  ) values (
    p_org_id, p_supplier_id, p_purchase_invoice_id, p_payment_date,
    p_amount_paid, coalesce(p_discount_amount, 0), p_payment_mode::public.payment_mode,
    nullif(btrim(p_reference_number), ''), nullif(btrim(p_notes), ''), p_actor_id,
    v_kw_date, v_source_seq, now(), p_actor_id, v_batch_id, 'live'
  ) returning id into v_payment_id;

  if p_amount_paid > 0 then
    insert into public.accounting_postings (
      organization_id, ledger, party_id, party_name, posting_date, document_date,
      reference_number, description, posting_sequence, event_type, debit_amount,
      credit_amount, source_type, source_id, provenance, posted_at, posted_by,
      batch_id, notes
    ) values (
      p_org_id, 'ap', p_supplier_id, v_supplier_name, v_kw_date, p_payment_date,
      nullif(btrim(p_reference_number), ''),
      coalesce(nullif(btrim(p_notes), ''), 'Supplier Payment'),
      v_seq, 'payment', p_amount_paid, 0, 'supplier_payment', v_payment_id,
      'live', now(), p_actor_id, v_batch_id, nullif(btrim(p_notes), '')
    ) returning id into v_posting_id;
  end if;

  if coalesce(p_discount_amount, 0) > 0 then
    v_discount_seq := case
      when p_amount_paid > 0 then public.next_posting_sequence(p_org_id)
      else v_seq
    end;
    insert into public.accounting_postings (
      organization_id, ledger, party_id, party_name, posting_date, document_date,
      reference_number, description, posting_sequence, event_type, debit_amount,
      credit_amount, source_type, source_id, provenance, posted_at, posted_by,
      batch_id, notes
    ) values (
      p_org_id, 'ap', p_supplier_id, v_supplier_name, v_kw_date, p_payment_date,
      nullif(btrim(p_reference_number), ''),
      coalesce(nullif(btrim(p_notes), ''), 'Supplier Settlement') || ' — Discount',
      v_discount_seq, 'adjustment', p_discount_amount, 0,
      'supplier_payment_discount', v_payment_id, 'live', now(), p_actor_id,
      v_batch_id, nullif(btrim(p_notes), '')
    ) returning id into v_discount_posting_id;
    if v_posting_id is null then
      v_posting_id := v_discount_posting_id;
    end if;
  end if;

  if p_purchase_invoice_id is not null then
    select coalesce(sum(
      coalesce(sp.amount_paid, 0) + coalesce(sp.discount_amount, 0)
    ), 0)
    into v_new_paid
    from public.supplier_payments sp
    where sp.organization_id = p_org_id
      and sp.purchase_invoice_id = p_purchase_invoice_id
      and sp.is_cancelled = false;

    if v_new_paid < 0 or v_new_paid > v_invoice.total_amount then
      raise exception 'Purchase invoice allocations do not reconcile to the invoice total';
    end if;

    update public.purchase_invoices
    set amount_paid = v_new_paid,
        balance_due = total_amount - v_new_paid,
        payment_status = case
          when v_new_paid = total_amount then 'paid'
          when v_new_paid > 0 then 'partial'
          else 'unpaid'
        end,
        updated_at = now()
    where id = p_purchase_invoice_id;
  end if;
  return query select v_payment_id, v_posting_id;
end;
$$;

create or replace function public.apply_supplier_advance(
  p_org_id uuid,
  p_actor_id uuid,
  p_supplier_advance_id uuid,
  p_purchase_invoice_id uuid
)
returns table(applied_amount numeric, balance_due numeric)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_advance supplier_advances%rowtype;
  v_invoice purchase_invoices%rowtype;
  v_applied numeric;
  v_new_paid numeric;
  v_new_balance numeric;
  v_active_allocated numeric;
  v_invalid_traces integer;
  v_existing_allocation uuid;
begin
  perform public.assert_accounting_actor(p_org_id, p_actor_id, array['owner', 'admin', 'manager']);
  perform set_config('fixops.allow_accounting_lifecycle_write', 'true', true);
  -- Stable order for advance application: invoice, supplier advance, then
  -- active allocation traces. Unapply follows the same order.
  select * into v_invoice from public.purchase_invoices
  where id = p_purchase_invoice_id and organization_id = p_org_id for update;
  if not found or v_invoice.status = 'cancelled' then raise exception 'Purchase invoice not found or cancelled'; end if;

  select * into v_advance from public.supplier_advances
  where id = p_supplier_advance_id and organization_id = p_org_id for update;
  if not found or v_advance.is_cancelled then raise exception 'Supplier advance not found or cancelled'; end if;
  if v_advance.balance <= 0 then raise exception 'Supplier advance has no balance'; end if;
  if v_invoice.supplier_id is distinct from v_advance.supplier_id then raise exception 'Advance supplier does not match invoice supplier'; end if;
  if v_invoice.posting_sequence is null then raise exception 'Advance requires a posted purchase invoice'; end if;
  if v_invoice.balance_due <= 0 then raise exception 'Purchase invoice is already settled'; end if;

  perform sp.id
  from public.supplier_payments sp
  where sp.organization_id = p_org_id
    and sp.supplier_advance_id = p_supplier_advance_id
    and sp.is_cancelled = false
  order by sp.id
  for update of sp;

  select
    coalesce(sum(sp.amount_paid), 0),
    count(*) filter (
      where sp.purchase_invoice_id is null
        or sp.amount_paid <= 0
        or coalesce(sp.discount_amount, 0) <> 0
        or sp.posting_sequence is not null
        or sp.organization_id is distinct from v_advance.organization_id
        or sp.supplier_id is distinct from v_advance.supplier_id
        or pi.id is null
        or pi.organization_id is distinct from v_advance.organization_id
        or pi.supplier_id is distinct from v_advance.supplier_id
    )
  into v_active_allocated, v_invalid_traces
  from public.supplier_payments sp
  left join public.purchase_invoices pi on pi.id = sp.purchase_invoice_id
  where sp.supplier_advance_id = p_supplier_advance_id
    and sp.is_cancelled = false;

  if v_advance.amount_utilized < 0
     or v_advance.balance < 0
     or v_advance.amount_utilized + v_advance.balance <> v_advance.amount
     or v_advance.amount_utilized <> v_active_allocated
     or v_invalid_traces > 0 then
    raise exception 'Supplier advance utilization does not reconcile to its active allocation traces';
  end if;

  select sp.id into v_existing_allocation
  from public.supplier_payments sp
  where sp.organization_id = p_org_id
    and sp.supplier_advance_id = p_supplier_advance_id
    and sp.purchase_invoice_id = p_purchase_invoice_id
    and sp.is_cancelled = false
  limit 1;
  if found then raise exception 'This supplier advance is already applied to the purchase invoice'; end if;

  v_applied := least(v_advance.balance, v_invoice.balance_due);
  update public.supplier_advances set amount_utilized = amount_utilized + v_applied,
    balance = balance - v_applied where id = p_supplier_advance_id;

  -- This trace is intentionally unposted: the advance debit was journaled when
  -- cash left, so application changes allocation only and must not debit AP again.
  insert into public.supplier_payments (
    organization_id, supplier_id, purchase_invoice_id, payment_date, amount_paid,
    discount_amount, payment_mode, notes, paid_by, supplier_advance_id
  ) values (
    p_org_id, v_advance.supplier_id, p_purchase_invoice_id,
    (now() at time zone 'Asia/Kuwait')::date, v_applied, 0, 'other',
    'Applied from advance ' || v_advance.advance_number, p_actor_id,
    p_supplier_advance_id
  );

  select coalesce(sum(
    coalesce(sp.amount_paid, 0) + coalesce(sp.discount_amount, 0)
  ), 0)
  into v_new_paid
  from public.supplier_payments sp
  where sp.organization_id = p_org_id
    and sp.purchase_invoice_id = p_purchase_invoice_id
    and sp.is_cancelled = false;

  if v_new_paid < 0 or v_new_paid > v_invoice.total_amount then
    raise exception 'Purchase invoice allocations do not reconcile to the invoice total';
  end if;

  v_new_balance := v_invoice.total_amount - v_new_paid;
  update public.purchase_invoices set amount_paid = v_new_paid,
    balance_due = v_new_balance,
    payment_status = case
      when v_new_balance = 0 then 'paid'
      when v_new_paid > 0 then 'partial'
      else 'unpaid'
    end,
    updated_at = now() where id = p_purchase_invoice_id;
  return query select v_applied, v_new_balance;
end;
$$;

create or replace function public.unapply_supplier_advance(
  p_org_id uuid,
  p_actor_id uuid,
  p_supplier_advance_id uuid,
  p_purchase_invoice_id uuid
)
returns table(unapplied_amount numeric, balance_due numeric)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_advance supplier_advances%rowtype;
  v_invoice purchase_invoices%rowtype;
  v_trace supplier_payments%rowtype;
  v_new_paid numeric;
  v_new_balance numeric;
begin
  perform public.assert_accounting_actor(p_org_id, p_actor_id, array['owner', 'admin', 'manager']);
  perform set_config('fixops.allow_accounting_lifecycle_write', 'true', true);

  -- Match application and purchase-invoice cancellation lock order: invoice,
  -- supplier advance, then active settlement traces in stable ID order.
  select * into v_invoice
  from public.purchase_invoices pi
  where pi.id = p_purchase_invoice_id and pi.organization_id = p_org_id
  for update;
  if not found or v_invoice.status = 'cancelled' then
    raise exception 'Purchase invoice not found or cancelled';
  end if;

  select * into v_advance
  from public.supplier_advances sa
  where sa.id = p_supplier_advance_id and sa.organization_id = p_org_id
  for update;
  if not found or v_advance.is_cancelled then
    raise exception 'Supplier advance not found or cancelled';
  end if;

  select * into v_trace
  from public.supplier_payments sp
  where sp.organization_id = p_org_id
    and sp.supplier_advance_id = p_supplier_advance_id
    and sp.purchase_invoice_id = p_purchase_invoice_id
    and sp.is_cancelled = false
  order by sp.id
  limit 1
  for update;
  if not found then raise exception 'Supplier advance allocation not found'; end if;
  if v_invoice.organization_id is distinct from v_advance.organization_id
     or v_trace.organization_id is distinct from v_advance.organization_id
     or v_invoice.supplier_id is distinct from v_advance.supplier_id
     or v_trace.supplier_id is distinct from v_advance.supplier_id then
    raise exception 'Supplier advance allocation organization or supplier does not reconcile';
  end if;

  if exists (
    select 1
    from public.supplier_payments sp
    where sp.organization_id = p_org_id
      and sp.supplier_advance_id = p_supplier_advance_id
      and sp.purchase_invoice_id = p_purchase_invoice_id
      and sp.is_cancelled = false
      and sp.id <> v_trace.id
  ) then
    raise exception 'Supplier advance has duplicate active allocations to this invoice';
  end if;

  if v_trace.amount_paid <= 0
     or v_trace.discount_amount <> 0
     or v_trace.posting_sequence is not null then
    raise exception 'Supplier advance allocation trace is invalid';
  end if;

  perform sp.id
  from public.supplier_payments sp
  where sp.organization_id = p_org_id
    and sp.supplier_advance_id = p_supplier_advance_id
    and sp.is_cancelled = false
  order by sp.id
  for update of sp;

  if v_advance.amount_utilized + v_advance.balance <> v_advance.amount
     or v_advance.amount_utilized <> (
       select coalesce(sum(sp.amount_paid), 0)
       from public.supplier_payments sp
       where sp.organization_id = p_org_id
         and sp.supplier_advance_id = p_supplier_advance_id
         and sp.is_cancelled = false
         and sp.purchase_invoice_id is not null
         and coalesce(sp.discount_amount, 0) = 0
         and sp.posting_sequence is null
     )
     or exists (
       select 1
       from public.supplier_payments sp
       left join public.purchase_invoices pi on pi.id = sp.purchase_invoice_id
       where sp.supplier_advance_id = p_supplier_advance_id
         and sp.is_cancelled = false
         and (
           sp.purchase_invoice_id is null
           or sp.amount_paid <= 0
           or coalesce(sp.discount_amount, 0) <> 0
           or sp.posting_sequence is not null
           or sp.organization_id is distinct from v_advance.organization_id
           or sp.supplier_id is distinct from v_advance.supplier_id
           or pi.id is null
           or pi.organization_id is distinct from v_advance.organization_id
           or pi.supplier_id is distinct from v_advance.supplier_id
         )
     ) then
    raise exception 'Supplier advance utilization does not reconcile to its active allocations';
  end if;

  update public.supplier_advances
  set amount_utilized = amount_utilized - v_trace.amount_paid,
      balance = balance + v_trace.amount_paid
  where id = p_supplier_advance_id;

  -- Keep the operational audit row but make it inactive. It never receives an
  -- accounting reversal because application itself was deliberately unposted.
  update public.supplier_payments
  set is_cancelled = true,
      cancelled_reason = 'Supplier advance allocation unapplied',
      cancelled_by = p_actor_id,
      cancelled_at = now()
  where id = v_trace.id;

  select coalesce(sum(
    coalesce(sp.amount_paid, 0) + coalesce(sp.discount_amount, 0)
  ), 0)
  into v_new_paid
  from public.supplier_payments sp
  where sp.organization_id = p_org_id
    and sp.purchase_invoice_id = p_purchase_invoice_id
    and sp.is_cancelled = false;

  if v_new_paid < 0 or v_new_paid > v_invoice.total_amount then
    raise exception 'Purchase invoice allocations do not reconcile to the invoice total';
  end if;

  v_new_balance := v_invoice.total_amount - v_new_paid;
  update public.purchase_invoices
  set amount_paid = v_new_paid,
      balance_due = v_new_balance,
      payment_status = case
        when v_new_balance = 0 then 'paid'
        when v_new_paid > 0 then 'partial'
        else 'unpaid'
      end,
      updated_at = now()
  where id = p_purchase_invoice_id;

  return query select v_trace.amount_paid, v_new_balance;
end;
$$;

