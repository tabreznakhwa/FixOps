       'inferred', null, null, 'Inferred historical posting'
from candidates b
join org_max m on m.organization_id = b.organization_id;

-- Preserve cancelled historical sources as original + inferred reversal instead
-- of omitting them. Reversal ordering follows the original global backfill range.
with org_max as (
  select organization_id, max(posting_sequence) as max_sequence
  from public.accounting_postings
  group by organization_id
),
cancelled as (
  select b.*,
         j.id as original_posting_id,
         m.max_sequence
           + row_number() over (
               partition by b.organization_id
               order by b.cancellation_date, b.source_rank, b.source_type, b.party_id, b.source_id
             ) as reversal_sequence
  from _postings_backfill b
  join public.accounting_postings j
    on j.organization_id = b.organization_id
   and j.source_type = b.source_type
   and j.source_id = b.source_id
   and j.event_type <> 'reversal'
  join org_max m on m.organization_id = b.organization_id
  where b.cancelled
    and not exists (
      select 1
      from public.accounting_postings existing_reversal
      where existing_reversal.reversal_of = j.id
    )
)
