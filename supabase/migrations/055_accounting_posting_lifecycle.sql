-- Once a source row has a posting tuple, its accounting identity and amount are
-- immutable. Lifecycle RPCs may set cancellation/reversal state, but direct
-- edits cannot rewrite the posted event and posted rows cannot be hard-deleted.
create or replace function public.guard_posted_accounting_source()
returns trigger
language plpgsql
as $$
declare
  v_field text;
begin
  if tg_op = 'DELETE' then
    if old.posting_sequence is not null then
      raise exception 'Posted accounting sources cannot be deleted; record a reversal instead';
    end if;
    return old;
  end if;

  if old.reversal_posting_id is not null
     and new.reversal_posting_id is distinct from old.reversal_posting_id then
    raise exception 'Accounting reversal metadata is immutable once set';
  end if;

  if old.posting_sequence is not null then
    -- The transaction-local marker lets lifecycle functions update protected
    -- source snapshots and reversal state. Original posting identity is never
    -- mutable, including from inside those functions.
    if new.organization_id is distinct from old.organization_id
       or new.posting_date is distinct from old.posting_date
       or new.posting_sequence is distinct from old.posting_sequence
       or new.posted_at is distinct from old.posted_at
       or new.posted_by is distinct from old.posted_by
       or new.posting_provenance is distinct from old.posting_provenance then
      raise exception 'Posted accounting metadata is immutable';
    end if;
    if new.posting_batch_id is distinct from old.posting_batch_id then
      raise exception 'Original posting batch metadata is immutable';
    end if;

    if coalesce(current_setting('fixops.allow_accounting_lifecycle_write', true), '') <> 'true' then
      foreach v_field in array tg_argv loop
        if to_jsonb(new) -> v_field is distinct from to_jsonb(old) -> v_field then
          raise exception 'Posted accounting field % is immutable', v_field;
        end if;
      end loop;
    end if;
  elsif new.posting_sequence is not null then
    if new.posting_date is null or new.posting_provenance is null then
      raise exception 'A complete posting tuple is required';
    end if;
  end if;

  return new;
end;
$$;
revoke all on function public.guard_posted_accounting_source() from public, anon, authenticated;

-- Advance-allocation traces are intentionally unposted, so the generic posted
-- source guard would otherwise permit direct edits or hard deletes. Only the
-- lifecycle RPCs may create/cancel these allocation records.
create or replace function public.guard_supplier_advance_allocation_trace()
returns trigger
language plpgsql
as $$
begin
  if coalesce(current_setting('fixops.allow_accounting_lifecycle_write', true), '') = 'true' then
    return case when tg_op = 'DELETE' then old else new end;
  end if;

  if (tg_op = 'DELETE' and old.supplier_advance_id is not null)
     or (tg_op = 'UPDATE' and (
       old.supplier_advance_id is not null or new.supplier_advance_id is not null
     ))
     or (tg_op = 'INSERT' and new.supplier_advance_id is not null) then
    raise exception 'Supplier advance allocation traces are managed only by accounting lifecycle functions';
  end if;

  return case when tg_op = 'DELETE' then old else new end;
end;
$$;
revoke all on function public.guard_supplier_advance_allocation_trace() from public, anon, authenticated;

-- An allocation trace must remain in the same tenant and supplier as both the
-- advance and purchase invoice it connects. This guard executes before the
-- generic lifecycle-write bypass, so even privileged/manual rows cannot create a
-- cross-tenant allocation by setting the transaction-local marker themselves.
create or replace function public.validate_supplier_advance_allocation_trace()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_advance record;
  v_invoice record;
begin
  -- When an existing trace is detached, validate the old relationship first so
  -- an UPDATE cannot use NULL to hide a pre-existing cross-tenant row.
  if tg_op = 'UPDATE'
     and old.supplier_advance_id is not null
     and (
       new.supplier_advance_id is distinct from old.supplier_advance_id
       or new.purchase_invoice_id is distinct from old.purchase_invoice_id
       or new.organization_id is distinct from old.organization_id
       or new.supplier_id is distinct from old.supplier_id
     ) then
    select sa.organization_id, sa.supplier_id
    into v_advance
    from public.supplier_advances sa
    where sa.id = old.supplier_advance_id;

    select pi.organization_id, pi.supplier_id
    into v_invoice
    from public.purchase_invoices pi
    where pi.id = old.purchase_invoice_id;

    if v_advance.organization_id is null
       or v_invoice.organization_id is null
       or old.organization_id is distinct from v_advance.organization_id
       or old.organization_id is distinct from v_invoice.organization_id
       or old.supplier_id is distinct from v_advance.supplier_id
       or old.supplier_id is distinct from v_invoice.supplier_id then
      raise exception 'Existing supplier advance allocation has inconsistent organization or supplier';
    end if;
  end if;

  if new.supplier_advance_id is null then
    return new;
  end if;

  select sa.organization_id, sa.supplier_id
  into v_advance
  from public.supplier_advances sa
  where sa.id = new.supplier_advance_id;

  select pi.organization_id, pi.supplier_id
  into v_invoice
  from public.purchase_invoices pi
  where pi.id = new.purchase_invoice_id;

  if v_advance.organization_id is null
     or v_invoice.organization_id is null
     or new.organization_id is distinct from v_advance.organization_id
     or new.organization_id is distinct from v_invoice.organization_id
     or new.supplier_id is distinct from v_advance.supplier_id
     or new.supplier_id is distinct from v_invoice.supplier_id then
    raise exception 'Supplier advance allocation must match one organization and supplier';
  end if;

  return new;
end;
$$;
revoke all on function public.validate_supplier_advance_allocation_trace()
  from public, anon, authenticated;

