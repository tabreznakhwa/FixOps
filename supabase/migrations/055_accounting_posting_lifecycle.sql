-- Posted journal rows are immutable: no updates, no hard deletes. All inserts
-- must come from a sanctioned lifecycle RPC, and reversals must exactly invert
-- their original posting.
create or replace function public.guard_accounting_posting_write()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_original public.accounting_postings%rowtype;
begin
  if tg_op = 'DELETE' then
    raise exception 'Accounting postings cannot be deleted; record a reversal instead';
  end if;
  if tg_op = 'UPDATE' then
    raise exception 'Accounting postings are immutable; record a reversal instead';
  end if;
  if coalesce(current_setting('fixops.allow_accounting_lifecycle_write', true), '') <> 'true' then
    raise exception 'Accounting postings must be written by an accounting lifecycle function';
  end if;

  if new.reversal_of is not null then
    select * into v_original
    from public.accounting_postings j
    where j.id = new.reversal_of
    for share;

    if not found
       or v_original.reversal_of is not null
       or new.event_type <> 'reversal'
       or new.organization_id <> v_original.organization_id
       or new.ledger <> v_original.ledger
       or new.party_id <> v_original.party_id
       or new.source_type is distinct from v_original.source_type
       or new.source_id is distinct from v_original.source_id
       or new.debit_amount <> v_original.credit_amount
       or new.credit_amount <> v_original.debit_amount then
      raise exception 'A reversal must exactly invert one original posting';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_guard_accounting_posting_write on public.accounting_postings;
create trigger trg_guard_accounting_posting_write
  before insert or update or delete on public.accounting_postings
  for each row
  execute function public.guard_accounting_posting_write();
