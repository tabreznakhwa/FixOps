-- ============================================================================
-- 055_accounting_posting_lifecycle.sql
-- Accounting posting lifecycle: a single authoritative posting journal, a
-- shared global posting sequence, deterministic inferred historical backfill,
-- immutability/delete guards, and service-role-only transactional RPCs for the
-- customer settlement workflows the schema already supports.
--
-- Model
-- -----
-- The ledgers previously assembled statements from operational rows
-- (invoices, payments, purchase invoices, supplier payments/advances, opening
-- balances). That projection is now replaced by one canonical journal,
-- `accounting_postings`, backfilled once from those sources and thereafter
-- written only by the RPCs below. Customer and Vendor ledgers read the journal,
-- so "posted events and reversals" is the single accounting truth and cancelled
-- documents remain visible as an original event plus a linked reversal event.
--
--   * AR: invoice/opening receivable is a debit; payment, credit note and
--     advance receipt are credits.
--   * AP: purchase invoice/opening payable is a credit; supplier payment,
--     discount and advance are debits. Purchase orders are commitments, not
--     postings, and are never journaled.
--   * Supplier-advance application trace rows (supplier_payments carrying
--     supplier_advance_id) are never journaled: the advance itself is already
--     the AP-reducing debit.
--
-- Posting sequence is one global, per-organization, monotonically increasing
-- value shared across every source, so ordering by (posting_date,
-- posting_sequence) is deterministic with no per-source collisions.
--
-- Live posting dates are generated by the database as
--     (now() at time zone 'Asia/Kuwait')::date
-- (a Kuwait live date), never trusted from the browser/server clock.
--
-- Historical backfill is deterministic: one original row per historical source,
-- provenance = 'inferred', a global sequence derived from (posting_date, source
-- rank, source type/id), and posted_at/posted_by left null because transition
-- timing is not recoverable. Draft invoices are not postings. Cancelled posted
-- sources retain their inferred original and receive a linked inferred reversal.
--
-- The functions follow migration 052: SECURITY DEFINER, `set search_path =
-- public`, active-actor + role + tenant validation inside the function,
-- advisory locks, and execute revoked from every role except service_role.
-- Application routes keep their own auth/role/org checks as the first line of
-- defence.
-- ============================================================================

