  on public.payments(opening_receivable_id)
  where opening_receivable_id is not null;
do $$
declare
  v_duplicate record;
  v_invalid record;
begin
  select
    sp.organization_id,
    sp.supplier_advance_id,
    sp.purchase_invoice_id,
    count(*) as allocation_count
  into v_duplicate
  from public.supplier_payments sp
  where sp.supplier_advance_id is not null
    and sp.purchase_invoice_id is not null
    and sp.is_cancelled = false
  group by sp.organization_id, sp.supplier_advance_id, sp.purchase_invoice_id
  having count(*) > 1
  order by sp.organization_id, sp.supplier_advance_id, sp.purchase_invoice_id
  limit 1;

  if found then
    raise exception
      'Duplicate active supplier advance allocation: org %, advance %, invoice %, rows %. Reconcile the allocation rows and source balances before rerunning migration 055.',
      v_duplicate.organization_id,
      v_duplicate.supplier_advance_id,
      v_duplicate.purchase_invoice_id,
      v_duplicate.allocation_count;
  end if;

  select
    sa.id,
    sa.organization_id,
    sa.supplier_id,
    sa.amount,
    sa.amount_utilized,
    sa.balance,
    sa.is_cancelled,
    coalesce(sum(sp.amount_paid) filter (where sp.is_cancelled = false), 0) as active_allocated,
    count(*) filter (
      where sp.is_cancelled = false
        and (
          sp.purchase_invoice_id is null
          or sp.amount_paid <= 0
          or coalesce(sp.discount_amount, 0) <> 0
          or sp.posting_sequence is not null
          or sp.organization_id is distinct from sa.organization_id
          or sp.supplier_id is distinct from sa.supplier_id
          or pi.id is null
          or pi.organization_id is distinct from sa.organization_id
          or pi.supplier_id is distinct from sa.supplier_id
        )
    ) as invalid_traces,
    count(*) filter (where sp.is_cancelled = false) as active_trace_count
  into v_invalid
  from public.supplier_advances sa
  left join public.supplier_payments sp on sp.supplier_advance_id = sa.id
  left join public.purchase_invoices pi on pi.id = sp.purchase_invoice_id
  group by sa.id, sa.organization_id, sa.supplier_id, sa.amount,
           sa.amount_utilized, sa.balance, sa.is_cancelled
  having sa.amount is null
      or sa.amount_utilized is null
      or sa.balance is null
      or sa.amount <= 0
      or sa.amount_utilized < 0
      or sa.balance < 0
      or sa.amount_utilized + sa.balance <> sa.amount
      or sa.amount_utilized <> coalesce(sum(sp.amount_paid) filter (where sp.is_cancelled = false), 0)
      or count(*) filter (
        where sp.is_cancelled = false
          and (
            sp.purchase_invoice_id is null
            or sp.amount_paid <= 0
            or coalesce(sp.discount_amount, 0) <> 0
            or sp.posting_sequence is not null
            or sp.organization_id is distinct from sa.organization_id
            or sp.supplier_id is distinct from sa.supplier_id
            or pi.id is null
            or pi.organization_id is distinct from sa.organization_id
            or pi.supplier_id is distinct from sa.supplier_id
          )
      ) > 0
      or (
        sa.is_cancelled
        and (
          sa.amount_utilized <> 0
          or sa.balance <> sa.amount
          or count(*) filter (where sp.is_cancelled = false) > 0
        )
      )
  order by sa.organization_id, sa.id
  limit 1;

  if found then
    raise exception
      'Supplier advance % does not reconcile (org %, amount %, utilized %, balance %, active allocations %, invalid traces %, cancelled %). Repair source totals/allocation traces before rerunning migration 055.',
      v_invalid.id,
      v_invalid.organization_id,
      v_invalid.amount,
      v_invalid.amount_utilized,
      v_invalid.balance,
      v_invalid.active_allocated,
      v_invalid.invalid_traces,
      v_invalid.is_cancelled;
  end if;
end
$$;

